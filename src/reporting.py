def _n(v: float) -> str:
    return f"{v:,.0f}"


def _p(v: float, d: int = 1) -> str:
    return "n/a" if v is None or not np.isfinite(v) else f"{v * 100:.{d}f}%"


def _ci(lo: float, hi: float, d: int = 1) -> str:
    return f"{lo * 100:.{d}f}% to {hi * 100:.{d}f}%"


def _table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = [
        "| " + " | ".join(str(c) for c in cols) + " |",
        "|" + "|".join("---" for _ in cols) + "|",
    ]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(str(v) for v in r) + " |")
    return "\n".join(out)


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GENERATED + text.strip() + "\n", encoding="utf-8")
    log.info("wrote %s", path.relative_to(DOCS_DIR.parent))


