# ---------------------------------------------------------------------------
# Static chart exports (matplotlib; from the real result tables)
# ---------------------------------------------------------------------------
def write_figures(
    cubes: dict[str, pd.DataFrame], bt: pd.DataFrame, res: dict[str, Any], params: dict
) -> None:
    """Chart exports to reports/figures/ (labelled as exports, not screenshots)."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})

    rm = cubes["roll_matrices"]
    t = rm[(rm.SLICE_TYPE == "overall") & (rm.VIEW == "A")]
    origins = C.MARKOV_ORDER[:6]
    piv = t.pivot_table(index="FROM_STATE", columns="TO_STATE", values="p").reindex(
        index=origins, columns=C.MARKOV_ORDER
    )
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.imshow(piv.to_numpy() * 100, cmap="Blues", vmin=0, vmax=100)
    ax.set_xticks(range(8), C.MARKOV_ORDER, rotation=30)
    ax.set_yticks(range(6), origins)
    for i in range(6):
        for j in range(8):
            v = piv.to_numpy()[i, j] * 100
            ax.text(
                j,
                i,
                f"{v:.1f}",
                ha="center",
                va="center",
                fontsize=7,
                color="white" if v > 50 else "#1F2937",
            )
    ax.set_title("Chart export: one-month roll-rate matrix, full window (%)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "roll_rate_matrix.png", dpi=150)
    plt.close(fig)

    vq = cubes["vintage_quarterly"]
    fig, ax = plt.subplots(figsize=(8, 4))
    qs = sorted(vq.VINTAGE_QTR.unique())[::3]
    for i, q in enumerate(qs):
        g = vq[q == vq.VINTAGE_QTR]
        ax.plot(
            g.MOB,
            g.ever_30p_rate * 100,
            color=plt.cm.Blues(0.35 + 0.6 * i / max(len(qs) - 1, 1)),
            label=g.VINTAGE_LABEL.iloc[0],
        )
    ax.set_xlabel("Months on book")
    ax.set_ylabel("Ever 30+ (% of vintage)")
    ax.set_title("Chart export: ever-30+ by vintage quarter (truncated at last observable MOB)")
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "vintage_ever30.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    sub = bt[(bt.horizon == 12) & (bt.metric == "mae_pp")]
    for model, col in (
        ("markov", "#1F5FBF"),
        ("mob_conditioned", "#0B1F3A"),
        ("static_mix", "#9AA5B1"),
        ("persistence", "#CBD5E1"),
    ):
        g = sub[sub.model == model].sort_values("origin")
        ax.plot(g.origin, g.value, marker="o", color=col, label=model)
        if g.lo.notna().any():
            ax.fill_between(g.origin, g.lo, g.hi, color=col, alpha=0.15)
    ax.set_xlabel("Forecast origin (relative month)")
    ax.set_ylabel("MAE across states (pp)")
    ax.set_title("Chart export: 12-month out-of-time error by origin")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "backtest_mae_12m.png", dpi=150)
    plt.close(fig)

    sp = cubes["stress_presets"]
    cur = params["stress"]["currency"]
    fig, ax = plt.subplots(figsize=(7, 3.8))
    scen = list(sp.scenario.unique())
    for k, h in enumerate(params["stress"]["horizons"]):
        g = sp[sp.horizon == h].set_index("scenario").reindex(scen)
        xs = np.arange(len(g)) + (k - 0.5) * 0.35
        ax.bar(
            xs,
            g.el,
            width=0.35,
            label=f"{h}M",
            color=["#6C93D6", "#0B1F3A"][k % 2],
            yerr=[g.el - g.el_lo, g.el_hi - g.el],
            capsize=3,
        )
    ax.set_xticks(np.arange(len(scen)), scen)
    ax.set_ylabel(f"Illustrative EL ({cur})")
    ax.set_title("Chart export: illustrative EL by scenario (assumed EAD and LGD)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "stress_el.png", dpi=150)
    plt.close(fig)
